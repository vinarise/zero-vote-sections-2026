"""Writes FINDINGS.md from the ledger, results.csv. Nothing in it is typed by hand.

  python make_findings.py
  python make_findings.py --piece path/to/en.md   check the readings against the piece's text, write nothing

It reads the rows of the latest run that no later row supersedes, and
piece_numbers.tsv, the list of every number the published piece states with the
ledger arm and field it should come from. Each of those numbers is formatted the way
the piece writes it and compared, character for character, with the piece's reading.
The script exits non-zero if any differs, after writing the file, so the difference
is on record. A number whose arm needs the private analyst labels (column `needs`) is
reported as such, not as a difference, when the run had no labels.

With --piece, it writes nothing and checks the other half of the chain: that each
`reads_as` string occurs in the section of the published piece that `where` names.
"""
import re
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from zvnb.ledger import Ledger  # noqa: E402

FMT = {
    "int": lambda v: f"{round(v):,}",
    "dec1": lambda v: f"{v:.1f}",
    "pct0": lambda v: f"{100 * v:.0f}%",
    "pct1": lambda v: f"{100 * v:.1f}%",
    "pct2": lambda v: f"{100 * v:.2f}%",
}


def num(x):
    return float(x) if x not in ("", None) else None


def main():
    led = Ledger(HERE / "results.csv", {})
    cur = led.current()
    run_id = cur[-1]["run_id"]
    rows = [r for r in cur if r["run_id"] == run_id]
    by_arm = {r["arm"]: r for r in rows}
    out, diffs = [], 0

    def numeric(x):
        try:
            float(str(x).replace(",", "").rstrip("%"))
            return True
        except ValueError:
            return str(x) == ""

    def table(head, body):
        right = [bool(body) and all(numeric(b[i]) for b in body) for i in range(len(head))]
        out.append("| " + " | ".join(head) + " |")
        out.append("|" + "|".join("---:" if r else "---" for r in right) + "|")
        out.extend("| " + " | ".join(str(c) for c in b) + " |" for b in body)
        out.append("")

    def f(x, d=1):
        v = num(x)
        return "" if v is None else (f"{v:,.0f}" if d == 0 else f"{v:.{d}f}")

    def pct(x, d=1):
        v = num(x)
        return "" if v is None else f"{100 * v:.{d}f}%"

    out += ["# Findings: zero-vote sections in Brazil's presidential runoffs", "",
            f"Generated by `make_findings.py` from `results.csv`, run `{run_id}`, {len(rows)} ledger rows. "
            "Every number names the ledger row it comes from. Do not edit this file by hand: rerun the notebook "
            "and this script.", "",
            f"Identity of the run: inputs `{rows[0]['inputs_sha256']}`, harness `{rows[0]['harness_sha256']}`, "
            f"environment `{rows[0]['environment_sha256']}`, config `{rows[0]['config_sha256']}`.", "",
            "Proportions carry their n and a Wilson 95% interval. Ratios of observed to expected zeros carry a "
            "95% interval from resampling polling places. A zero is a section with at least one valid vote in "
            "which the side had none. The PT side is Fernando Haddad in 2018 and Lula after him. The PL side is "
            "Jair Bolsonaro in 2018 (for the PSL) and 2022, and Flávio Bolsonaro in 2026.", ""]

    # 1. The piece's numbers.
    with open(HERE / "piece_numbers.tsv", newline="") as fh:
        pn = list(csv.DictReader(fh, delimiter="\t"))
    body = []
    labels_ran = any(r["measure"] == "register_text_agreement" for r in rows)
    needs_labels = 0
    for p in pn:
        arms = p["arm"].split("+")
        missing = [a for a in arms if a not in by_arm]
        if missing and p.get("needs") == "labels" and not labels_ran:
            body.append([p["id"], p["where"], p["stated"], "not computed", p["field"], "", "",
                         "needs the private analyst labels, absent from this run"])
            needs_labels += 1
            continue
        if missing:
            body.append([p["id"], p["where"], p["stated"], "missing", p["field"], "", "", "no"])
            diffs += 1
            continue
        val = sum(num(by_arm[a][p["field"]]) for a in arms)
        got = FMT[p["format"]](val)
        same = got == p["reads_as"]
        diffs += not same
        body.append([p["id"], p["where"], p["stated"], " + ".join(by_arm[a]["row_id"] for a in arms), p["field"],
                     f"{val:.10g}", got, "yes" if same else f"NO, the piece reads {p['reads_as']}"])
    out += ["## 1. Every number the published piece states, against the ledger", "",
            f"{len(pn) - diffs - needs_labels} of {len(pn)} numbers come out identical. "
            + ("None differs." if not diffs else f"{diffs} differ, and each is a finding, not a correction.")
            + (f" {needs_labels} need the private analyst labels, which this run did not have." if needs_labels else ""),
            ""]
    table(["Id", "Where in the piece", "The piece says", "Ledger row", "Field", "Ledger value", "Formatted", "Identical"],
          body)

    # 2. Zero-vote sections.
    zc = [r for r in rows if r["measure"] == "zero_count"]
    out += ["## 2. Zero-vote sections by year, side and minimum size", ""]
    table(["Row", "Year", "Side", "At least n valid votes", "Zero sections k", "Sections n", "Share %",
           "Wilson 95% low %", "Wilson 95% high %", "Other side's votes in them"],
          [[r["row_id"], r["year"], r["side"], r["min_valid_votes"], r["k"], f(r["n"], 0), pct(r["share"], 4),
            pct(r["share_ci_low"], 4), pct(r["share_ci_high"], 4), f(r["votes_other"], 0)] for r in zc])

    # 3. Models.
    oe = [r for r in rows if r["measure"] == "observed_vs_expected" and r["event"] == "zero" and r["min_valid_votes"] == "1"]
    best = {(r["year"], r["side"], r["model"]): r["k"] == "1" for r in rows if r["measure"] == "is_best_model"}
    out += ["## 3. Observed against expected zeros, zero event, at least one valid vote", "",
            "Pre-registered models: B-mun, B-place, BB-mun, BB-place. Added after results: EB-place, EB-r1. "
            "BB-place (v1 code) is the first implementation of BB-place, kept to show the effect of its fix. "
            "The best model has the highest log score of the six.", ""]
    table(["Row", "Year", "Side", "Model", "Status", "Observed k", "Expected", "99.9% bound (exact)", "U1 fires",
           "Ratio", "Ratio 95% low", "Ratio 95% high", "Log score", "Best"],
          [[r["row_id"], r["year"], r["side"], r["model"], r["prereg_status"], r["k"], f(r["expected"]),
            r["upper_99_9_exact"], r["u1_fires_exact"], f(r["ratio"]), f(r["ratio_ci_low"]), f(r["ratio_ci_high"]),
            f(r["log_score"]), "yes" if best.get((r["year"], r["side"], r["model"])) else ""] for r in oe])

    # 4. Registers.
    out += ["## 4. The 2026 zero sections by register category (added after results)", "",
            "The method was fixed in `EXTERNAL-CHECK-PLAN.md` before the register check ran.", ""]
    table(["Row", "Side", "Category", "Basis", "Zero sections k", "Of n", "Share %", "Wilson 95% low %", "Wilson 95% high %"],
          [[r["row_id"], r["side"], r["category"] or "all categories", r["scope"], r["k"], r["n"], pct(r["share"]), pct(r["share_ci_low"]),
            pct(r["share_ci_high"])] for r in rows if r["measure"] in ("zero_category", "zero_basis")])
    table(["Row", "Category (registers, 1 km)", "Side", "Sections n", "Zero sections k", "Share %", "Wilson 95% high %"],
          [[r["row_id"], r["category"], r["side"], f(r["n"], 0), r["k"], pct(r["share"], 2), pct(r["share_ci_high"], 2)]
           for r in rows if r["measure"] == "category_table" and r["scope"] == "registers, 1 km"])

    # 5. Panel.
    out += ["## 5. Places followed from 2022 to 2026 (added after results)", "",
            "The share uses a Wilson interval. The place-cluster interval is the one the piece quotes.", ""]
    table(["Row", "Definition", "Year", "Side", "Places", "Zero sections k", "Sections n", "Share %",
           "Wilson low %", "Wilson high %", "Place-cluster low %", "Place-cluster high %"],
          [[r["row_id"], r["category"], r["year"], r["side"], f(r["value"], 0), r["k"], f(r["n"], 0), pct(r["share"]),
            pct(r["share_ci_low"]), pct(r["share_ci_high"]), pct(r["ratio_ci_low"]), pct(r["ratio_ci_high"])]
           for r in rows if r["measure"] == "panel_zero_rate"])

    # 6. Consistency.
    out += ["## 6. Consistency checks between the published files", ""]
    table(["Row", "Check", "Year", "Differences or matches k", "Compared n", "What n counts"],
          [[r["row_id"], r["category"], r["year"], r["k"], f(r["n"], 0), r["n_label"]]
           for r in rows if r["measure"] == "consistency"])

    # 7. Decision.
    out += ["## 7. The rules registered in EXPERIMENT.md, read against the ledger", ""]
    out += ["Each row says whether the expectation registered in EXPERIMENT.md held. The registration states one "
            "for U1 only: that it fires for the binomial models in every year and on both sides. The other rules "
            "were registered without an expected outcome.", ""]
    table(["Row", "Rule", "Checks", "Year", "Side", "k", "n", "Value", "Registered expectation held", "Note"],
          [[r["row_id"], r["category"], r["scope"] or ("all registered" if r["category"] == "U1" else ""),
            r["year"], r["side"], r["k"], r["n"],
            f(r["value"], 4), r["expectation_held"], r["note"]]
           for r in rows if r["measure"] == "decision"])

    # 8. Checks.
    out += ["## 8. Known-answer tests, reproduction and the map files", ""]
    table(["Row", "Measure", "Category", "Year", "Side", "k", "n", "What n counts"],
          [[r["row_id"], r["measure"], r["category"], r["year"], r["side"], r["k"], r["n"], r["n_label"]]
           for r in rows if r["run_class"] in ("known-answer", "check") and r["measure"] != "bmun_recomputed"])
    out += [f"The rest of the {len(rows)} rows (every event, size and model, regions, round 1, local shares) are in "
            "`results.csv`. Rows labelled exploratory come from stage 6, written after the U2 result.", ""]

    (HERE / "FINDINGS.md").write_text("\n".join(out))
    print(f"FINDINGS.md: {len(pn) - diffs - needs_labels} of {len(pn)} piece numbers identical, "
          f"{needs_labels} need the labels, run {run_id}, {len(rows)} rows")
    return 1 if diffs else 0


# Parts of the piece that `where` names without a heading of their own.
ALIASES = {"the models table": "What the models say and don't"}


def sections(text):
    """{heading text: body} for every heading of the piece."""
    parts = re.split(r"^#{1,4} +(.+?) *$", text, flags=re.M)
    return {parts[i].strip().replace("\u2019", "'"): parts[i + 1] for i in range(1, len(parts) - 1, 2)}


def check_piece(path):
    text = Path(path).read_text(encoding="utf-8")
    secs = sections(text)
    with open(HERE / "piece_numbers.tsv", newline="") as fh:
        pn = list(csv.DictReader(fh, delimiter="\t"))
    bad, whole = [], []
    for p in pn:
        names = [p["where"].split(",")[0].strip()] + re.findall(r"and '(.+)'$", p["where"])
        names += [h for alias, h in ALIASES.items() if alias in p["where"]]
        # A quoted name may be the start of a heading: 'Did anything change' is "Did anything change in 2026".
        found = sorted({h for n in names for h in secs if h == n or h.startswith(n + " ")})
        if found:
            if not any(p["reads_as"] in secs[n] for n in found):
                bad.append(f"{p['id']}: '{p['reads_as']}' is not in the section {' or '.join(found)}")
        else:
            whole.append(p["id"])
            if p["reads_as"] not in text:
                bad.append(f"{p['id']}: '{p['reads_as']}' is not in the piece")
    print(f"{len(pn) - len(bad)} of {len(pn)} readings occur in the piece, {len(pn) - len(whole)} of them checked "
          f"inside the section `where` names, {len(whole)} in the whole text because `where` names no heading "
          f"({', '.join(whole) or 'none'})")
    for b in bad:
        print("  " + b)
    return 1 if bad else 0


if __name__ == "__main__":
    if "--piece" in sys.argv:
        sys.exit(check_piece(sys.argv[sys.argv.index("--piece") + 1]))
    sys.exit(main())
